"""Consolidate runs and compute every number in the report from the raw events.

  python -m benchmarks.analysis build     # results/results.csv, results/event_logs.jsonl, results/tables.json
  python -m benchmarks.analysis tables    # print the markdown tables

Definitions (also stated in the report):
  * Percentiles: linear interpolation (numpy default). p50 needs n>=1, p95 n>=20, p99 n>=100; below
    that the cell shows n/m (not meaningful) unless a table says otherwise (Table 3 uses p95 from n>=10,
    marked with a dagger).
  * TTFT = time from request admission to the first CONTENT token generated by the model (queueing,
    limiter waits and retry waits before it are included; they are also reported separately).
  * Total = admission to completion of the final response (after verification).
  * Outcome buckets are disjoint: ok | timed-out-or-given-up (status timeout, or a retry/queue/deadline
    give-up) | rate-limited (rejected or refused because of a limit) | error.
  * Tokens per answer = mean (prompt+completion) tokens of requests that produced a cited answer.
  * Cost per 1,000 answers is NOTIONAL: Groq on-demand list price for gpt-oss-120b ($0.15 / 1M input,
    $0.60 / 1M output tokens). The free tier itself bills $0.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

from app.config import ROOT_DIR
from app.monitoring.metrics import CSV_COLUMNS, fmt_pct, load_events, percentile, write_results_csv
from app.pipeline.pipeline import GIVEN_UP_REASONS

RESULTS = Path(ROOT_DIR) / "results"
RUNS = RESULTS / "runs"
PRICE_IN, PRICE_OUT = 0.15 / 1e6, 0.60 / 1e6

# order in results.csv / report
RUN_ORDER = ["quality_real", "real_steady", "real_burst", "steady", "burst", "overload", "rpm_halved",
             "daily_exhausted", "retry_none", "retry_naive", "retry_relayflow"]
CSV_SCENARIO = {"real_steady": "steady", "real_burst": "burst", "overload": "sustained_overload"}
SCENARIO_LABEL = {"steady": "Steady", "burst": "Burst", "overload": "Sustained overload",
                  "rpm_halved": "Per-minute limit halved", "daily_exhausted": "Daily budget exhausted"}


def load_run(key: str) -> dict:
    d = RUNS / key
    ev = load_events(d / "events.jsonl")
    grades = json.loads((d / "grades.json").read_text(encoding="utf-8")) if (d / "grades.json").exists() else {}
    meta = json.loads((d / "run_meta.json").read_text(encoding="utf-8")) if (d / "run_meta.json").exists() else {}
    for e in ev:
        g = grades.get(e["request_id"])
        e["answer_grade"] = g["grade"] if g else ""
        e["grade_reasons"] = g["reasons"] if g else []
    return {"key": key, "events": ev, "meta": meta}


def available_runs() -> list[str]:
    return [k for k in RUN_ORDER if (RUNS / k / "events.jsonl").exists()]


def consolidate() -> list[dict]:
    out: list[dict] = []
    for k in available_runs():
        for e in load_run(k)["events"]:
            e = dict(e)
            e["run_key"] = k
            e["scenario"] = CSV_SCENARIO.get(e["run_key"], e["scenario"])
            out.append(e)
    return out


# ---------------------------------------------------------------------------------------------
def outcome_bucket(e: dict) -> str:
    if e["status"] == "ok":
        return "ok"
    if e["status"] == "timeout" or e.get("terminal_reason") in GIVEN_UP_REASONS:
        return "given_up"
    if e["status"] == "rate_limited":
        return "rate_limited"
    return "error"


def answered(e: dict) -> bool:
    return e["status"] == "ok" and e.get("answer_type") == "answer"


def scenario_rows(run: dict) -> dict:
    ev, meta = run["events"], run["meta"]
    n = len(ev)
    b = Counter(outcome_bucket(e) for e in ev)
    ok = [e for e in ev if e["status"] == "ok" and e.get("first_token_ms") is not None]
    ans = [e for e in ev if answered(e)]
    toks_in = [e["tokens_in"] or 0 for e in ans]
    toks_out = [e["tokens_out"] or 0 for e in ans]
    tok_per_answer = float(np.mean([a + o for a, o in zip(toks_in, toks_out)])) if ans else None
    cost = 1000 * float(np.mean([a * PRICE_IN + o * PRICE_OUT for a, o in zip(toks_in, toks_out)])) if ans else None
    ftl = [e["first_token_ms"] for e in ok]
    tot = [e["total_ms"] for e in ev if e["status"] == "ok" and e.get("total_ms") is not None]
    return {
        "key": run["key"], "label": meta.get("label"), "source": meta.get("source"),
        "requests": n, "duration_s": meta.get("duration_s"), "offered_per_min": meta.get("offered_rate_per_min"),
        "ttft": fmt_pct(ftl), "total": fmt_pct(tot), "n_ttft": len(ftl), "n_total": len(tot),
        "ok_pct": 100 * b["ok"] / n, "rate_limited_pct": 100 * b["rate_limited"] / n,
        "given_up_pct": 100 * b["given_up"] / n, "error_pct": 100 * b["error"] / n,
        "retries_per_request": sum(e["retries"] for e in ev) / n,
        "peak_queue": (meta.get("scheduler_stats") or {}).get("peak_queue_len"),
        "tokens_per_answer": tok_per_answer, "cost_per_1000": cost, "n_answers": len(ans),
        "queue_ms_p50_p95": fmt_pct([e["queue_ms"] for e in ev if e.get("queue_ms") is not None], (50, 95)),
    }


def retrieval_rows(events: list[dict]) -> list[dict]:
    rows = []
    for cfg in ("A", "B", "C"):
        ev = [e for e in events if e["scenario"] == f"retrieval_{cfg}"]
        if not ev:
            continue
        n = len(ev)
        g = Counter(e["answer_grade"] for e in ev)
        ans = [e for e in ev if answered(e)]
        called = [e for e in ev if (e.get("tokens_in") or 0) > 0]

        def pct(vals: list[float], q: int) -> str:
            p = percentile(vals, q) if q == 50 else (percentile(vals, 95) or (
                float(np.percentile(vals, 95)) if len(vals) >= 10 else None))
            if p is None:
                return "n/m"
            dag = "†" if q == 95 and len(vals) < 20 else ""
            return f"{p:.0f}{dag}"

        ft = [e["first_token_ms"] for e in ans if e.get("first_token_ms") is not None]
        tt = [e["total_ms"] for e in ans]
        rows.append({
            "cfg": cfg, "n": n, "n_answers": len(ans), "n_called": len(called),
            "correct_pct": 100 * g["correct"] / n, "wrong_pct": 100 * g["wrong"] / n,
            "refused_correctly_pct": 100 * g["refused_correctly"] / n,
            "refused_wrongly_pct": 100 * g["refused_wrongly"] / n,
            "ungraded_pct": 100 * g[""] / n,
            "tokens_per_answer": float(np.mean([(e["tokens_in"] or 0) + (e["tokens_out"] or 0) for e in ans])) if ans else None,
            "tokens_per_question": float(np.mean([(e["tokens_in"] or 0) + (e["tokens_out"] or 0) for e in ev])),
            "ttft_p50": pct(ft, 50), "ttft_p95": pct(ft, 95), "total_p50": pct(tt, 50), "total_p95": pct(tt, 95),
            "repairs": sum(e["repairs"] for e in ev),
            "api_calls": sum(e["llm_calls"] for e in ev),
        })
    return rows


def slowest_request(events: list[dict], run_key: str | None = None) -> dict | None:
    cand = [e for e in events if e["status"] == "ok" and e.get("first_token_ms") is not None
            and (run_key is None or e["run_key"] == run_key)]
    return max(cand, key=lambda e: e["total_ms"]) if cand else None


def breakdown(e: dict) -> dict:
    """Latency components of one request, from its own timestamps and timers."""
    admit, start = e["ts_queue_entry"], e["ts_processing_start"]
    first, end = e["ts_first_token"], e["ts_completion"]
    total = e["total_ms"]
    pre = (e["analysis_ms"] + e["retrieval_ms"] + e["decision_ms"])
    return {
        "request_id": e["request_id"], "run": e["run_key"], "total_ms": total,
        "queue_wait_ms": e["queue_ms"], "analysis_retrieval_decision_ms": pre,
        "limiter_wait_ms": e["limiter_wait_ms"], "retry_wait_ms": e["retry_wait_ms"],
        "provider_ms": e["provider_ms"], "verification_ms": e["verification_ms"], "tool_ms": e["tool_ms"],
        "first_token_ms": e["first_token_ms"],
        "after_first_token_ms": total - e["first_token_ms"],
        "retries": e["retries"], "attempts": [(a["http_status"], a["error_type"], round(a["total_ms"]), round(a["backoff_s"], 2))
                                              for a in e["attempts"]],
        "ts": {"queue_entry": admit, "processing_start": start, "first_token": first, "completion": end},
        "accounted_ms": e["queue_ms"] + pre + e["limiter_wait_ms"] + e["retry_wait_ms"] + e["provider_ms"] + e["verification_ms"],
    }


def build() -> dict:
    events = consolidate()
    RESULTS.mkdir(parents=True, exist_ok=True)
    n = write_results_csv(events, RESULTS / "results.csv")
    with (RESULTS / "event_logs.jsonl").open("w", encoding="utf-8") as f:
        for e in events:
            f.write(json.dumps(e, ensure_ascii=False, default=str) + "\n")
    tables: dict = {"n_rows": n, "runs": {}}
    for k in available_runs():
        run = load_run(k)
        if k == "quality_real":
            continue
        tables["runs"][k] = scenario_rows(run)
    tables["retrieval"] = retrieval_rows([e for e in events if e["run_key"] == "quality_real"])
    for k in ("overload", "burst", "retry_naive"):
        s = slowest_request(events, k)
        if s:
            tables.setdefault("slowest", {})[k] = breakdown(s)
    (RESULTS / "tables.json").write_text(json.dumps(tables, indent=1, default=str), encoding="utf-8")
    return tables


def f1(x: float | None) -> str:
    return "not measured" if x is None else f"{x:.1f}"


def print_tables(t: dict) -> None:
    print("\nTable 2a")
    for k, r in t["runs"].items():
        print(f"| {r['label'] or k} | {r['source']} | {r['requests']} | {r['duration_s']} | {r['offered_per_min']} | {r['ttft']} | {r['total']} |")
    print("\nTable 2b")
    for k, r in t["runs"].items():
        print(f"| {r['label'] or k} | {r['ok_pct']:.1f} | {r['rate_limited_pct']:.1f} | {r['given_up_pct']:.1f} | "
              f"{r['retries_per_request']:.2f} | {r['peak_queue']} | {f1(r['tokens_per_answer'])} | {f1(r['cost_per_1000'])} |")
    print("\nTable 3")
    for r in t["retrieval"]:
        print(r)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    tabs = build()
    if cmd in ("tables", "build"):
        print_tables(tabs)
